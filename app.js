const CATEGORY_LABELS = {
  study: "📚 Study",
  coding: "💻 Coding",
  content: "✍️ Content"
};

// ---------- State ----------
let activeCategory = "all";
let searchText = "";

// ---------- DOM ----------
const cardsEl = document.getElementById("cards");
const searchBox = document.getElementById("searchBox");
const resultCount = document.getElementById("resultCount");
const noResults = document.getElementById("noResults");
const filterButtons = document.querySelectorAll(".filter-btn");

// ---------- Render ----------
function render() {
  const query = searchText.trim().toLowerCase();
  const visible = PROMPTS.filter(item => {
    const inCategory = activeCategory === "all" || item.category === activeCategory;
    const inSearch = !query ||
      item.title.toLowerCase().includes(query) ||
      item.prompt.toLowerCase().includes(query) ||
      item.when.toLowerCase().includes(query) ||
      CATEGORY_LABELS[item.category].toLowerCase().includes(query);
    return inCategory && inSearch;
  });

  cardsEl.innerHTML = "";
  visible.forEach(item => {
    const card = document.createElement("article");
    card.className = "card";

    const top = document.createElement("div");
    top.className = "card-top";
    const heading = document.createElement("h2");
    heading.textContent = item.title;
    const badge = document.createElement("span");
    badge.className = "badge badge-" + item.category;
    badge.textContent = CATEGORY_LABELS[item.category];
    top.appendChild(heading);
    top.appendChild(badge);

    const when = document.createElement("p");
    when.className = "when";
    when.textContent = item.when;

    const pre = document.createElement("pre");
    pre.textContent = item.prompt;

    const copyBtn = document.createElement("button");
    copyBtn.className = "copy-btn";
    copyBtn.textContent = "📋 Copy Prompt";
    copyBtn.addEventListener("click", () => copyPrompt(item.prompt, copyBtn));

    card.appendChild(top);
    card.appendChild(when);
    card.appendChild(pre);
    card.appendChild(copyBtn);
    cardsEl.appendChild(card);
  });

  resultCount.textContent = "Showing " + visible.length + " of " + PROMPTS.length + " prompts";
  noResults.hidden = visible.length !== 0;
}

// ---------- Copy to clipboard (with fallback) ----------
function copyPrompt(text, button) {
  const done = () => {
    const original = "📋 Copy Prompt";
    button.textContent = "✅ Copied!";
    button.classList.add("copied");
    setTimeout(() => {
      button.textContent = original;
      button.classList.remove("copied");
    }, 1600);
  };

  if (navigator.clipboard && window.isSecureContext) {
    navigator.clipboard.writeText(text).then(done).catch(() => fallbackCopy(text, done));
  } else {
    fallbackCopy(text, done);
  }
}

function fallbackCopy(text, done) {
  const area = document.createElement("textarea");
  area.value = text;
  area.style.position = "fixed";
  area.style.opacity = "0";
  document.body.appendChild(area);
  area.select();
  try {
    document.execCommand("copy");
    done();
  } catch (err) {
    // Clipboard unavailable — nothing more we can do in a plain file page.
  }
  document.body.removeChild(area);
}

// ---------- Events ----------
searchBox.addEventListener("input", () => {
  searchText = searchBox.value;
  render();
});

filterButtons.forEach(btn => {
  btn.addEventListener("click", () => {
    filterButtons.forEach(b => b.classList.remove("active"));
    btn.classList.add("active");
    activeCategory = btn.dataset.category;
    render();
  });
});

// ---------- Start ----------
render();
