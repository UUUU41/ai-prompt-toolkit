PLACEHOLDER_RE = re.compile(r"\[([^\]]+)\]")


def list_templates():
    """Print all templates, grouped by category, with numbers."""
    print("\n================ AI PROMPT TOOLKIT ================")
    current_category = None
    for i, (category, title, when, _prompt) in enumerate(TEMPLATES, start=1):
        if category != current_category:
            current_category = category
            print(f"\n--- {category} ---")
        print(f"{i:>2}. {title}")
        print(f"     When: {when}")
    print("\n===================================================")


def pick_template():
    """Ask the user for a template number; return its index or None to quit."""
    while True:
        raw = input(f"\nEnter a template number (1-{len(TEMPLATES)}), or 'q' to quit: ").strip()
        if raw.lower() in ("q", "quit", "exit"):
            return None
        try:
            number = int(raw)
        except ValueError:
            print("That was not a number. Please try again.")
            continue
        if 1 <= number <= len(TEMPLATES):
            return number - 1
        print(f"Please enter a number between 1 and {len(TEMPLATES)}.")


def fill_template(prompt):
    """Ask for each [PLACEHOLDER] value and return the finished prompt."""
    placeholders = []
    for name in PLACEHOLDER_RE.findall(prompt):
        if name not in placeholders:
            placeholders.append(name)
    filled = prompt
    for name in placeholders:
        while True:
            value = input(f"  {name}: ").strip()
            if value:
                break
            print("  (Please type something — an empty value would leave a gap in the prompt.)")
        filled = filled.replace("[" + name + "]", value)
    return filled


def main():
    print("Welcome to the AI Prompt Toolkit!")
    print("Pick a template, fill in your details, and copy the finished prompt into any AI chat tool.")
    try:
        while True:
            list_templates()
            index = pick_template()
            if index is None:
                break
            _category, title, _when, prompt = TEMPLATES[index]
            print(f"\nYou picked: {title}")
            print("Now fill in the details:")
            finished = fill_template(prompt)
            print("\n----- YOUR READY-TO-PASTE PROMPT -----")
            print(finished)
            print("---------------------------------------")
            again = input("\nMake another prompt? (y/n): ").strip().lower()
            if again not in ("y", "yes"):
                break
    except (EOFError, KeyboardInterrupt):
        print()  # clean line after Ctrl+C / end of input
    print("Goodbye! Happy prompting. 🤖")
    return 0


if __name__ == "__main__":
    sys.exit(main())
